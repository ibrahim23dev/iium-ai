import type { Attachment, ModelId } from "@/types/chat";

/** Development-only response stream. Replace this adapter with a server route when a provider is configured. */
export async function* streamMockResponse(prompt: string, model: ModelId, attachments: Attachment[], signal: AbortSignal) {
  void prompt;
  const answer = attachments.length
    ? `**Local preview only:** I can see ${attachments.length} attachment${attachments.length === 1 ? "" : "s"} (${attachments.map((item) => item.name).join(", ")}), but this preview does not analyze file contents. Connect an AI provider to work with your attachments.`
    : `**Local preview only:** ${model === "default" ? "IIUM AI Default" : model} is not connected to an AI provider, so this response was not generated by an AI model. Configure a server-side provider integration to enable real responses.`;
  const words = answer.split(" ");
  for (let i = 0; i < words.length; i += 3) {
    if (signal.aborted) return;
    await new Promise((resolve) => setTimeout(resolve, 35));
    yield `${words.slice(i, i + 3).join(" ")}${i + 3 < words.length ? " " : ""}`;
  }
}
